def swap (x, y):
    x[1], y[1] = y[1], x[1]
    print(x, y)
    x, y = y, x
    print(x, y)
    x[0][1], y[0][1] = y[0][1], x[0][1]
    print(x, y)
    x[0][0][1],y[1][0][1] = y[1][0][1], x[0][0][1]
    print(x, y)

x, y = [[[1,2],[3,4]],[[5,6],[7,8]]], [[[9,'A'],['B','C']],[['D','E'],['F',0]]]

swap(x, y)
print(x, y)